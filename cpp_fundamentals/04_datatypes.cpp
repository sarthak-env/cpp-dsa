#include <iostream>
using namespace std;

int main()
{
    int age = 21;  // int is used to store whole numbers
    float marks = 85.5; // float is used to store decimal numbers
    double price = 99.99; // double is used to store decimal numbers with more precision
    char grade = 'A'; // char is used to store a single character
    bool isStudent = true;  // bool is used to store true or false values
    string name = "Sarthak"; // string is used to store text

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Marks: " << marks << endl;
    cout << "Price: " << price << endl;
    cout << "Grade: " << grade << endl;
    cout << "Student: " << isStudent << endl;

    return 0;
}

// Here, endl means end line. It moves the cursor to the next line after printing